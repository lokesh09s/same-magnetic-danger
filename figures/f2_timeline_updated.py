"""F2 data timeline: one row per data period; every boundary date is parsed from a numbers.json macro.
Graphic generated by code written by Claude Code (AI).
Usage (from paper_template/figures): python f2_timeline.py"""
import matplotlib.pyplot as plt, matplotlib.dates as mdates, pandas as pd
from matplotlib.patches import Patch
from matplotlib.lines import Line2D
from figstyle import INK, INK2, GRID, FULL, status_style, numbers, save

N = numbers()
D = lambda m: pd.Timestamp(N[m]["value"])          # KeyError names any missing macro
dev0, dev1 = (int(y) for y in N["SetDevYears"]["value"].split("–"))
test = [int(y) for y in N["SetTestYears"]["value"].split(",")]
gap = [y for y in range(dev1 + 1, min(test)) if y not in test]          # 2020: between dev and test
sens = int(N["SetSensYear"]["value"])                                  # 2022: inside the test span, not a test year
assert len(gap) == 1 and min(test) < sens < max(test) and sens not in test, (gap, sens)
conf0, conf1, p0 = D("SetConfStart"), D("SetConfEnd"), D("TimeProspStart")
looks = [("Look 1", pd.Timestamp("2026-09-03 23:00"), pd.Timestamp("2026-10-09")), ("Look 2", D("TimeLookTwoEnd"), D("TimeLookTwoRun"))]
yr = lambda y: (pd.Timestamp(y, 1, 1), pd.Timestamp(y + 1, 1, 1))
fmt = lambda t: t.strftime("%Y-%m-%d")

C_CONF, _, _, L_CONF = status_style("PRE-REGISTERED CONFIRMATORY")
C_SEC, _, _, L_SEC = status_style("PRE-REGISTERED SECONDARY")
C_DEV, _, _, L_DEV = status_style("EXPLORATORY (dev)")
PRE = dict(facecolor=C_CONF, edgecolor=C_CONF)                          # held-out test, 2025-26 confirmation
SEC = dict(facecolor="white", edgecolor=C_SEC, hatch="....")             # 2022: pre-registered sensitivity set, never pooled
PROSP = dict(facecolor="white", edgecolor=C_CONF, ls="--")              # prospective looks: pre-registered, not yet run
DEV = dict(facecolor="white", edgecolor=C_DEV, hatch="////")
EXCL = dict(facecolor="white", edgecolor=INK2, hatch="xxx")
rows = [(f"development {N['SetDevYears']['value']}", [(pd.Timestamp(dev0, 1, 1), yr(dev1)[1])], DEV),
        (f"{gap[0]} excluded", [yr(gap[0])], EXCL),
        (f"held-out test\n{N['SetTestYears']['value']}", [yr(y) for y in test], PRE),
        (f"{sens} sensitivity", [yr(sens)], SEC),
        (f"confirmation {N['SetConfYears']['value']}", [(conf0, conf1)], PRE)] + \
       [(f"prospective {n}", [(p0, e)], PROSP) for n, e, _ in looks]

def bars(ax, rows, h):
    for i, (_, spans, st) in enumerate(rows):
        for a, b in spans:
            ax.barh(len(rows) - 1 - i, mdates.date2num(b) - mdates.date2num(a), left=mdates.date2num(a), height=h, lw=0.8, **st)
    ax.set_yticks(range(len(rows)), [r[0] for r in rows][::-1])
    ax.set_ylim(-0.6, len(rows) - 0.4)
    ax.tick_params(axis="y", length=0)
    ax.spines["left"].set_visible(False)

fig, (a1, a2) = plt.subplots(2, 1, figsize=(FULL, 4.0), gridspec_kw=dict(height_ratios=[7, 4.6], hspace=0.42))
fig.subplots_adjust(left=0.25, right=0.975, top=0.95, bottom=0.13)   # keeps all text inside FULL width
z0, z1 = conf0 - pd.Timedelta(days=60), looks[-1][2] + pd.Timedelta(days=380)   # ponytail: margin = room for the Look 2 label (checked below)
bars(a1, rows, 0.62)
a1.axvspan(z0, z1, color=GRID, alpha=0.45, lw=0, zorder=0)
a1.set_xlim(pd.Timestamp(dev0, 1, 1), pd.Timestamp(looks[-1][2].year, 7, 1))   # 2010 to mid-2027
lo, hi = (mdates.num2date(v).replace(tzinfo=None) for v in a1.get_xlim())
assert all(lo <= a and b <= hi for _, sp, _ in rows for a, b in sp), (lo, hi)
a1.xaxis.set_major_locator(mdates.YearLocator(2)); a1.xaxis.set_minor_locator(mdates.YearLocator(1))
a1.xaxis.set_major_formatter(mdates.DateFormatter("%Y"))
a1.set_title("(a) all data periods", loc="left")
a1.legend(handles=[Patch(**PRE, label=L_CONF), Patch(**SEC, label=L_SEC), Patch(**PROSP, label="pre-registered, not yet run"),
                   Patch(**DEV, label=L_DEV), Patch(**EXCL, label="excluded"),
                   Patch(color=GRID, alpha=0.45, lw=0, label="span enlarged in (b)")],
          loc="lower left", handlelength=1.6, borderaxespad=0.2, labelspacing=0.4)
zrows = rows[-3:]
bars(a2, zrows, 0.5)
a2.set_yticklabels([r[0] for r in zrows[:0:-1]] + [zrows[0][0] + "\n(TEST 1, TEST 2)"])
a2.text(conf0 + (conf1 - conf0) / 2, 2, f"{fmt(conf0)} → {fmt(conf1)}", ha="center", va="center", color="white")
labs = []
for i, (_, e, run) in enumerate(looks):
    y = 1 - i
    if i != 0: a2.plot([run], [y], "|", color=INK, ms=9, mew=1.6)
    a2.text(p0 - pd.Timedelta(days=12), y, f"t from {fmt(p0)}", ha="right", va="center", color=INK2)
    label = "end ≤3 Sep 2026, 23:00 TAI\nearly, once; amended 9 Oct" if i == 0 else f"set end ≤ {fmt(e)}\nrun ≥ {fmt(run)}"
    labs.append(a2.text(run + pd.Timedelta(days=14), y, label, ha="left", va="center", color=INK2, linespacing=1.0))
a2.set_xlim(z0, z1)
assert z0 <= conf0 and all(run <= z1 for *_, run in looks), (z0, z1)
a2.xaxis.set_major_locator(mdates.YearLocator()); a2.xaxis.set_minor_locator(mdates.MonthLocator((4, 7, 10)))
a2.xaxis.set_major_formatter(mdates.DateFormatter("%Y"))
a2.set_title("(b) confirmation and prospective sets", loc="left")
a2.legend(handles=[Line2D([], [], ls="none", marker="|", color=INK, ms=9, mew=1.6, label="run not before")],
          loc="upper right", handlelength=1.0, borderaxespad=0.2)
a2.set_xlabel("calendar date (ticks: 1 January)")
fig.canvas.draw()                                    # Look labels: inside (b) with a margin, and not touching each other
m = 0.06 * fig.dpi                                   # ~4 pt
ax_bb, (b1, b2) = a2.get_window_extent(), (t.get_window_extent() for t in labs)
assert all(b.x1 <= ax_bb.x1 - m for b in (b1, b2)), (b1, b2, ax_bb)
assert b1.y0 - b2.y1 >= m, (b1, b2)
print(save(fig, "F2_timeline_updated", "f2_timeline_updated.py"))
